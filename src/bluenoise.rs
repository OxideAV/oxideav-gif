//! A 64 × 64 blue-noise threshold map for ordered dithering.
//!
//! An ordered dither adds a position-dependent offset to every pixel
//! before the nearest-entry search. A recursive (Bayer) threshold matrix
//! gives a regular cross-hatch; a *blue-noise* map — one whose
//! thresholds have no low-frequency structure, so that the pixels below
//! any level are spread as evenly as possible — gives an irregular,
//! grain-like pattern with no visible tile.
//!
//! The map is a rank ordering of the 4096 positions built from an
//! energy field: every chosen position contributes a bell-shaped bump
//! (wrapping around the tile edges), so the field is high inside
//! clusters and low inside voids. The table below is the output of the
//! `generator` module in this file (kept under `cfg(test)`, where a
//! test reruns it against the table), committed so that the first
//! dithered picture does not pay for building it.
//!
//! 1. Scatter a tenth of the positions from a fixed-seed generator, then
//!    relax them: move the point at the field's maximum (the tightest
//!    cluster) to the field's minimum among free positions (the largest
//!    void) until the point just removed is itself the largest void.
//! 2. Rank the relaxed points by removing the tightest cluster each
//!    time: the last one removed gets rank 0.
//! 3. Starting again from the relaxed set, fill the largest void each
//!    time and give it the next rank, until the tile is full.

const SIDE: usize = 64;
const AREA: usize = SIDE * SIDE;

/// The generator the committed [`RANKS_TABLE`] came from; the unit test
/// reruns it and compares. Integer arithmetic throughout, so the result
/// is the same on every platform.
///
/// A bump is the product of two rows of binomial coefficients,
/// `C(14, 7 + dx) × C(14, 7 + dy)` — the integer stand-in for a Gaussian
/// of standard deviation `√(14 / 4) ≈ 1.87` positions.
#[cfg(test)]
mod generator {
    use super::{AREA, SIDE};

    /// Bumps reach this many positions from their centre.
    const REACH: i32 = 7;

    struct Field {
        energy: Vec<u64>,
        taken: Vec<bool>,
        bump: Vec<u64>,
    }

    impl Field {
        fn new() -> Self {
            let span = (2 * REACH + 1) as usize;
            // Row 14 of Pascal's triangle.
            let mut row = vec![1u64];
            for _ in 0..2 * REACH {
                let mut next = vec![1u64; row.len() + 1];
                for i in 1..row.len() {
                    next[i] = row[i - 1] + row[i];
                }
                row = next;
            }
            let mut bump = vec![0; span * span];
            for (y, wy) in row.iter().enumerate() {
                for (x, wx) in row.iter().enumerate() {
                    bump[y * span + x] = wx * wy;
                }
            }
            Field {
                energy: vec![0; AREA],
                taken: vec![false; AREA],
                bump,
            }
        }

        fn set(&mut self, at: usize, taken: bool) {
            self.taken[at] = taken;
            let (x, y) = ((at % SIDE) as i32, (at / SIDE) as i32);
            let span = (2 * REACH + 1) as usize;
            for dy in -REACH..=REACH {
                let yy = (y + dy).rem_euclid(SIDE as i32) as usize;
                for dx in -REACH..=REACH {
                    let xx = (x + dx).rem_euclid(SIDE as i32) as usize;
                    let w = self.bump[(dy + REACH) as usize * span + (dx + REACH) as usize];
                    let cell = &mut self.energy[yy * SIDE + xx];
                    *cell = if taken { *cell + w } else { *cell - w };
                }
            }
        }

        /// Taken position with the highest energy (first on a tie).
        fn tightest_cluster(&self) -> usize {
            let mut best = (0u64, usize::MAX);
            for (i, (&e, &t)) in self.energy.iter().zip(&self.taken).enumerate() {
                if t && (best.1 == usize::MAX || e > best.0) {
                    best = (e, i);
                }
            }
            best.1
        }

        /// Free position with the lowest energy (first on a tie).
        fn largest_void(&self) -> usize {
            let mut best = (u64::MAX, usize::MAX);
            for (i, (&e, &t)) in self.energy.iter().zip(&self.taken).enumerate() {
                if !t && (best.1 == usize::MAX || e < best.0) {
                    best = (e, i);
                }
            }
            best.1
        }
    }

    pub(super) fn build() -> Vec<u16> {
        let mut field = Field::new();
        let seeds = AREA / 10;
        let mut state = 0x2545_F491u32;
        let mut placed = 0;
        while placed < seeds {
            state = state.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
            let at = (state >> 8) as usize % AREA;
            if !field.taken[at] {
                field.set(at, true);
                placed += 1;
            }
        }
        // Relax; the bound only guards against a cycle.
        for _ in 0..AREA * 4 {
            let cluster = field.tightest_cluster();
            field.set(cluster, false);
            let void = field.largest_void();
            field.set(void, true);
            if void == cluster {
                break;
            }
        }
        let relaxed = field.taken.clone();
        let mut rank = vec![0u16; AREA];
        for r in (0..seeds).rev() {
            let at = field.tightest_cluster();
            field.set(at, false);
            rank[at] = r as u16;
        }
        for (at, &t) in relaxed.iter().enumerate() {
            if t {
                field.set(at, true);
            }
        }
        for r in seeds..AREA {
            let at = field.largest_void();
            field.set(at, true);
            rank[at] = r as u16;
        }
        rank
    }
}

